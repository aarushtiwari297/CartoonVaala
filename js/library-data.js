// Helper: Render Memory Visual (Photo with Vector Fallback)
function getMemoryVisualHTML(item, isModal) {
  const photoClass = isModal ? "memory-modal-photo" : "memory-card-photo";
  
  if (item.image) {
    return `
      <div class="memory-photo-container">
        <img src="${item.image}" alt="${item.title}" class="${photoClass}" loading="lazy">
        <div class="memory-photo-vignette" aria-hidden="true"></div>
      </div>
    `;
  }
  
  return getMemoryVisualSVG(item);
}

